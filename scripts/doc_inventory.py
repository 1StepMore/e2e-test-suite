#: Scenario-count claim forms validated against the DERIVED library numbers
#: (total, tier-1, tier-2, tier-3). The expected count is never hardcoded —
#: the ``scenarios/**/*.yaml`` glob is the source of truth, and these docs
#: must state what the library actually contains. Each entry is
#: ``(pattern, rel-path, group-idx -> expected-slot)``; group 1..N map to
#: slots (0=total, 1=tier-1, 2=tier-2, 3=tier-3).
_SCENARIO_CLAIM_SITES: tuple[tuple[re.Pattern[str], str, tuple[int, ...]], ...] = (
    (
        re.compile(r"(\d+)-scenario library"),
        ".opencode/skills/omni-validation/SKILL.md",
        (0,),
    ),
    (
        re.compile(
            r"scenario library \*\*(\d+)\*\* = \*\*(\d+) tier-1 / (\d+) tier-2 / (\d+) tier-3\*\*"
        ),
        ".opencode/skills/omni-docmap/SKILL.md",
        (0, 1, 2, 3),
    ),
    (
        re.compile(r"scenarios/: (\d+) yaml files; tiers=\{'1': (\d+), '2': (\d+), '3': (\d+)\}"),
        ".opencode/skills/omni-docmap/SKILL.md",
        (0, 1, 2, 3),
    ),
)


def _check_scenario_claim_sites(
    root: Path, total: int, tiers: dict[str, int], failures: list[str]
) -> None:
    """Validate docs that state a scenario count / tier split against the
    derived library numbers (total + tiers['1'/'2'/'3']). Skipped when the
    claim-site doc is absent (e.g. a test fixture tree)."""
    derived = (total, tiers.get("1", 0), tiers.get("2", 0), tiers.get("3", 0))
    for pattern, rel, idxs in _SCENARIO_CLAIM_SITES:
        path = root / rel
        if not path.exists():
            continue
        for m in pattern.finditer(read_text(path)):
            claimed = tuple(int(m.group(i + 1)) for i in idxs)
            expected = tuple(derived[i] for i in idxs)
            if claimed != expected:
                failures.append(
                    f"{rel}: scenario claim {m.group(0)!r} does not match the "
                    f"derived library ({total} yaml files, "
                    f"tiers={dict(sorted(tiers.items()))}) — update the doc "
                    f"when the scenario library changes"
                )


def check_scenarios(root: Path, failures: list[str]) -> None:
    """Scenario count DERIVED from the ``scenarios/**/*.yaml`` glob (never a
    pinned number); claim-site docs stating a count/tier-split must match it.
    Input formats >= 13; '13+' claims.

    Skipped (report-only, not a failure) when ``scenarios/`` is absent. The
    library glob is the source of truth — a legitimate scenario addition or
    removal never fails the gate by itself; only a doc claiming a stale count
    does (update the claim-site docs when the library changes).
    """
    scenarios = root / "scenarios"
    if not scenarios.is_dir():
        print("  scenarios/: absent -> skip (report-only, not a failure)")
        return
    yamls = sorted(p for p in scenarios.rglob("*.yaml") if p.is_file())
    total = len(yamls)
    tiers: dict[str, int] = {}
    for p in yamls:
        tier = "1"  # missing tier field defaults to tier 1 (plan: 82/3/1)
        for line in read_text(p).splitlines():
            if re.match(r"tier\s*:", line.strip()):
                tier = line.split(":", 1)[1].strip()
                break
        tiers[tier] = tiers.get(tier, 0) + 1
    print(f"  scenarios/: {total} yaml files; tiers={dict(sorted(tiers.items()))}")
    _check_scenario_claim_sites(root, total, tiers, failures)

    opp_dir = scenarios / "opp"
    if opp_dir.is_dir():
        opp_count = len([p for p in opp_dir.glob("*.yaml") if p.is_file()])
        print(f"  scenarios/opp: {opp_count} input-format scenarios")
        if opp_count < 13:
            failures.append(f"scenarios/opp: {opp_count} input formats, expected >= 13")
        for rel in ("AGENTS.md", "README.md"):
            path = root / rel
            if path.exists() and "13+" not in read_text(path):
                failures.append(f"{rel} must claim '13+' input formats")


def check_test_matrix(root: Path, failures: list[str]) -> None:
    """Canonical test-matrix (131/64/0) + nightly (14) claims; skip absent files."""
    proj = root / "PROJECT_STATUS.md"
    if proj.exists():
        text = read_text(proj)
        if "131 PASS, 64 SKIP, 0 FAIL" not in text:
            failures.append("PROJECT_STATUS.md must carry the canonical '131 PASS, 64 SKIP, 0 FAIL'")
        for m in re.finditer(r"(\d+)\s+PASS\b", text):
            if m.group(1) != "131":
                failures.append(f"PROJECT_STATUS.md claims {m.group(1)} PASS, canonical is 131")
    else:
        print("  PROJECT_STATUS.md: absent -> skip (report-only)")
    for rel in ("TESTS.md", "ACCEPTED_GAPS.md", "docs/SECURITY_AUDIT.md"):
        path = root / rel
        if not path.exists():
            continue
        for m in re.finditer(r"(\d+)\s+PASS\b", read_text(path)):
            if m.group(1) not in ("131", "0"):
                failures.append(f"{rel} claims {m.group(1)} PASS outside the canonical matrix")
    tes = root / "TESTS.md"
    if tes.exists() and "14 nightly tests" not in read_text(tes):
        failures.append("TESTS.md must carry '14 nightly tests'")
    ulw = root / "reports" / "ulw-loop-design.md"
    if ulw.exists():
        if "(--collect-only; canonical: 14)" not in read_text(ulw):
            failures.append("reports/ulw-loop-design.md must carry '(--collect-only; canonical: 14)'")


def check_version_sync(root: Path, failures: list[str]) -> None:
    """Delegate version-doc sync to scripts/sync_version_docs.py --check."""
    sync = root / "scripts" / "sync_version_docs.py"
    if not sync.exists():
        print("  scripts/sync_version_docs.py: absent -> warn-skip")
        return
    try:
        proc = subprocess.run(
            ["python3", str(sync), "--check"],
            cwd=str(root),
            capture_output=True,
            text=True,
            timeout=120,
        )
    except (subprocess.SubprocessError, OSError) as exc:
        failures.append(f"scripts/sync_version_docs.py --check could not run: {exc}")
        return
    if proc.returncode != 0:
        failures.append(
            f"scripts/sync_version_docs.py --check failed (rc={proc.returncode}): "
            f"{(proc.stdout or proc.stderr).strip()}"
        )


