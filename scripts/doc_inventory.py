def categorize(rel: Path) -> str:
    """Map a docs-relative path to its category (filename override first)."""
    name = rel.name
    for pattern, cat in FILENAME_CATEGORY_OVERRIDES:
        if pattern.search(name):
            return cat
    if "archive" in rel.parts:
        return "archive"
    for seg in CATEGORY_SEGMENTS:
        if seg in rel.parts:
            return f"docs/{seg}"
    return "docs/root" if len(rel.parts) == 1 else "docs/dev"


def status_of(rel: Path) -> str:
    """'archived' for paths under docs/archive/, else 'active'."""
    return "archived" if "archive" in rel.parts else "active"


def scan_docs(docs: Path = DOCS, out: Path = OUT) -> list[dict[str, Any]]:
    """Return one row per docs/**/*.md, *.yaml or *.json file (sorted, stable).

    ``docs``/``out`` are parameters so ``--root`` trees can be scanned too.
    """
    paths: set[Path] = set()
    for suffix in ("*.md", "*.yaml", "*.json"):
        if docs.is_dir():
            paths.update(docs.rglob(suffix))
    rows: list[dict[str, Any]] = []
    for path in sorted(paths, key=lambda p: p.relative_to(docs).as_posix()):
        if path == out:
            continue  # never list the inventory itself (breaks idempotency)
        rel = path.relative_to(docs)
        text = read_text(path)
        m = DOC_TYPE_RE.search(text)
        rows.append(
            {
                "path": rel.as_posix(),
                "lines": len(text.splitlines()),
                "category": categorize(rel),
                "status": status_of(rel),
                "doc_type": m.group(1).strip() if m else "\u2014",
            }
        )
    return rows


def esc(value: str) -> str:
    """Escape a value for a Markdown table cell."""
    return value.replace("|", "\\|")


def render_report(rows: list[dict[str, Any]]) -> str:
    """Build the full Markdown report (header + summary + inventory)."""
    total_lines = sum(r["lines"] for r in rows)
    active = sum(1 for r in rows if r["status"] == "active")
    archived = sum(1 for r in rows if r["status"] == "archived")

    lines: list[str] = [HEADER, "", "# Documentation Inventory", ""]
    lines.append(
        "AUTO-GENERATED inventory of Markdown/YAML/JSON files under `docs/`, "
        "produced by `scripts/doc_inventory.py`. **Do not edit by hand.** "
        "Regenerate:"
    )
    lines.append("")
    lines.append("```bash")
    lines.append("python3 scripts/doc_inventory.py          # regenerate this file")
    lines.append("python3 scripts/doc_inventory.py --check  # source-truth consistency (exit 0 = clean)")
    lines.append("```")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|--------|-------|")
    lines.append(f"| Total files | {len(rows)} |")
    lines.append(f"| Total lines | {total_lines} |")
    lines.append(f"| Active files | {active} |")
    lines.append(f"| Archived files | {archived} |")
    for cat in CATEGORY_ORDER:
        cat_rows = [r for r in rows if r["category"] == cat]
        if not cat_rows:
            continue
        cat_lines = sum(r["lines"] for r in cat_rows)
        lines.append(f"| Category \u2014 {cat} | {len(cat_rows)} files / {cat_lines} lines |")
    lines.append("")
    lines.append("## Inventory")
    lines.append("")
    lines.append("| Relative path | Lines | Category | Status | Doc-type |")
    lines.append("|---------------|------:|----------|--------|----------|")
    for r in rows:
        lines.append(
            f"| `{esc(r['path'])}` | {r['lines']} | {esc(r['category'])} "
            f"| {esc(r['status'])} | {esc(r['doc_type'])} |"
        )
    return "\n".join(lines) + "\n"


