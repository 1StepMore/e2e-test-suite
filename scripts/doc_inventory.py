#: Suite headers that carry a per-module tool count.
_SUITE_HEADER_RE = re.compile(r"### (OPP|OL|ORF) MCP Server\s+\((\d+)\s+tools?\)")
#: Claude MCP server names.
_CLAUDE_SERVER_RE = re.compile(r"### (opp-mcp-server|ol-mcp|orf-mcp-server)\s+\((\d+)\s+tools?\)")
#: agent-pipeline-guide per-module tool counts. The live guide writes
#: "**OPP MCP (7 tools):**" — the optional ":" after ")" is the T-11 blind
#: spot this regex now covers.
_GUIDE_MODULE_RE = re.compile(r"\*\*(OPP|OL|ORF) MCP\s+\((\d+)\s+tools?\):?\*\*")
#: agent-pipeline-guide "Server Overview" table rows ("| OPP MCP | 7 | ...").
_GUIDE_TABLE_RE = re.compile(r"\|\s*(OPP|OL|ORF) MCP\s*\|\s*(\d+)\s*\|")
#: API_STABILITY §2.2 prose ("**OPP** is on its 0.6.x line. ... the 7 MCP
#: tools"). The count can sit past a sentence boundary, so the gap is
#: line-bounded (not period-bounded) and capped at 60 chars.
_API_MODULE_PROSE_RE = re.compile(r"(OPP|OL|ORF)[^\n]{0,60}?(\d+) MCP tools")
#: "7 + 21 + 6 = 34 tools" / "9+21+7=37 工具" / "= 37 module tools" /
#: "= 37 个模块工具" module-sum forms (OPP+OL+ORF). Qualifier words between
#: the total and the tool noun ("module", "个模块") are allowed.
_MODULE_SUM_RE = re.compile(
    r"(\d+)\s*\+\s*(\d+)\s*\+\s*(\d+)\s*=\s*(\d+)"
    r"(?:\s+\w+)*(?:\s*(?:tools?|工具))"
)
#: docs/PRD.md "OPP (7 tools), OL (21 tools), ORF (6 tools)" list form.
_PRD_LIST_RE = re.compile(r"(OPP|OL|ORF)\s*\((\d+)\s+tools?\)")
#: Per-repo README "MCP Surface Mastery (7 MCP tools)" counts.
_README_MCP_RE = re.compile(r"\((\d+)\s+MCP tools\)")
#: ARCHITECTURE diagram server rows ("opp-mcp-server<br/>7 tools").
_ARCH_DIAGRAM_RE = re.compile(r"(opp-mcp-server|ol-mcp|orf-mcp-server)\s*<br/?>\s*(\d+)\s+tools?")
#: ARCHITECTURE "Total: 21 tools".
_ARCH_TOTAL_RE = re.compile(r"Total:\s*(\d+)\s+tools")
#: "7 + 8 + 6 = 21 tools" in API_STABILITY / ARCHITECTURE.
_SEVEN_EIGHT_SIX_RE = re.compile(r"7\s*\+\s*8\s*\+\s*6\s*=\s*(\d+)\s+tools?")
#: "(N tools total: ...)" in SECURITY_AUDIT.
_TOTAL_PAREN_RE = re.compile(r"\((\d+)\s+tools?\s+total")
#: Per-module AGENTS.md "MCP tools (N total)".
_MODULE_AGENTS_ANY_RE = re.compile(r"MCP tools\s*\((\d+)\s+total\)")
#: ARCHITECTURE source tree rows: "mcp/server.py ← MCP server (N tools)".
_TREE_SERVER_RE = re.compile(r"MCP server\s*\((\d+)\s+tools?\)")
#: ARCHITECTURE source tree row for OL: "src/ol_mcp/ ← MCP server (N tools)".
_TREE_OL_RE = re.compile(r"src/ol_mcp/.*MCP server\s*\((\d+)\s+tools?\)")

# --- Module-doc claim shapes (issue #10) -----------------------------------
# These scan ``Omni_*/docs/**/*.md`` (and the module READMEs for the two
# prose shapes). Module attribution is DERIVED from the enclosing module
# directory, never hardcoded per file, so one regex serves all three modules.
#: OL docs/API.md "The server registers N tools".
_MODULE_DOC_REGISTERS_RE = re.compile(r"registers\s+(\d+)\s+tools?\b")
#: OL docs/ARCHITECTURE.md "N tools, all in `TOOL_REGISTRY`".
_MODULE_DOC_ALL_IN_REGISTRY_RE = re.compile(r"(\d+)\s+tools?,?\s+all in\s+`?TOOL_REGISTRY`?")
#: OPP docs/API.md "All N tool functions".
_MODULE_DOC_ALL_TOOL_FUNCTIONS_RE = re.compile(r"All\s+(\d+)\s+tool functions\b")
#: ORF docs/ARCHITECTURE.md source-tree fence "MCP server (N tools)".
_MODULE_DOC_MCP_SERVER_RE = re.compile(r"MCP server\s*\((\d+)\s+tools?\)")
#: Module README prose "exposing N tools".
_MODULE_README_EXPOSING_RE = re.compile(r"exposing\s+(\d+)\s+tools?\b")
#: Module README source-tree fence "server.py ... N tools".
_MODULE_README_SERVER_TREE_RE = re.compile(r"server\.py[^\n]*?(\d+)\s+tools?\b")
#: Module-doc self-declared version match: "vX.Y.Z (matches `pyproject.toml`)".
_MODULE_DOC_VERSION_MATCH_RE = re.compile(r"v(\d+\.\d+\.\d+)\s*\(matches\s+`?pyproject\.toml`?\)")

#: Module directory -> module key, in report order (OPP, OL, ORF).
_MODULE_DOC_DIRS: tuple[tuple[str, str], ...] = (
    ("Omni_Pre_Processor", "opp"),
    ("Omni_Localizer", "ol"),
    ("Omni_Re_Formatter", "orf"),
)


def _fail(failures: list[str], rel: str, module: str, claimed: int, expected: int) -> None:
    if claimed != expected:
        failures.append(f"{rel} claims {module} {claimed} tools, source truth is {expected}")


def _check_module_sum(failures: list[str], rel: str, text: str, source: dict[str, int]) -> None:
    total = source["opp"] + source["ol"] + source["orf"]
    for m in _MODULE_SUM_RE.finditer(text):
        opp_c, ol_c, orf_c, total_c = (int(g) for g in m.groups())
        _fail(failures, rel, "opp", opp_c, source["opp"])
        _fail(failures, rel, "ol", ol_c, source["ol"])
        _fail(failures, rel, "orf", orf_c, source["orf"])
        _fail(failures, rel, "total", total_c, total)


def check_claim_sites(root: Path, source: dict[str, int], failures: list[str]) -> None:
    """Verify every tool-count claim in the drift-prone docs matches source truth."""
    total = source["opp"] + source["ol"] + source["orf"]

    # Suite README.md + AGENTS.md: "### OPP MCP Server (9 tools)".
    for rel in ("README.md", "AGENTS.md"):
        path = root / rel
        if not path.exists():
            continue
        for m in _SUITE_HEADER_RE.finditer(read_text(path)):
            _fail(failures, rel, m.group(1).lower(), int(m.group(2)), source[m.group(1).lower()])

    # CLAUDE.md: "### opp-mcp-server (7 tools)".
    path = root / "CLAUDE.md"
    if path.exists():
        for m in _CLAUDE_SERVER_RE.finditer(read_text(path)):
            mod = SERVER_MODULE[m.group(1)]
            _fail(failures, "CLAUDE.md", mod, int(m.group(2)), source[mod])

    # docs/agent-pipeline-guide.md: "**OPP MCP (7 tools):**" + "all 34 tools
    # across" + the Server Overview table.
    path = root / "docs" / "agent-pipeline-guide.md"
    if path.exists():
        text = read_text(path)
        for m in _GUIDE_MODULE_RE.finditer(text):
            _fail(failures, "docs/agent-pipeline-guide.md", m.group(1).lower(), int(m.group(2)), source[m.group(1).lower()])
        for m in _GUIDE_TABLE_RE.finditer(text):
            _fail(failures, "docs/agent-pipeline-guide.md", m.group(1).lower(), int(m.group(2)), source[m.group(1).lower()])
        m = re.search(r"all\s+(\d+)\s+tools\s+across", text)
        if m:
            _fail(failures, "docs/agent-pipeline-guide.md", "total", int(m.group(1)), total)

    # docs/ARCHITECTURE.md: diagram rows, Total line, 7+8+6 line, source tree.
    path = root / "docs" / "ARCHITECTURE.md"
    if path.exists():
        text = read_text(path)
        for m in _ARCH_DIAGRAM_RE.finditer(text):
            mod = SERVER_MODULE[m.group(1)]
            _fail(failures, "docs/ARCHITECTURE.md", mod, int(m.group(2)), source[mod])
        for m in _ARCH_TOTAL_RE.finditer(text):
            _fail(failures, "docs/ARCHITECTURE.md", "total", int(m.group(1)), total)
        for m in _SEVEN_EIGHT_SIX_RE.finditer(text):
            _fail(failures, "docs/ARCHITECTURE.md", "total", int(m.group(1)), total)
        lines = text.splitlines()
        for i, ln in enumerate(lines):
            if "mcp/server.py" in ln and _TREE_SERVER_RE.search(ln):
                claimed = int(_TREE_SERVER_RE.search(ln).group(1))
                ctx = "\n".join(lines[max(0, i - 1):i + 3])
                mod = "opp" if "0.9" in ctx else "orf"
                _fail(failures, "docs/ARCHITECTURE.md", mod, claimed, source[mod])
        for m in _TREE_OL_RE.finditer(text):
            _fail(failures, "docs/ARCHITECTURE.md", "ol", int(m.group(1)), source["ol"])

    # docs/API_STABILITY.md: "7 + 8 + 6 = 21 tools" + named "OPP public CLI and
    # 7 MCP tools" + §2.2 prose ("... the 7 MCP tools") + the 9+21+7=37 sum.
    path = root / "docs" / "API_STABILITY.md"
    if path.exists():
        text = read_text(path)
        for m in _SEVEN_EIGHT_SIX_RE.finditer(text):
            _fail(failures, "docs/API_STABILITY.md", "total", int(m.group(1)), total)
        for m in re.finditer(r"(OPP|OL|ORF) public CLI and (\d+) MCP tools", text):
            _fail(failures, "docs/API_STABILITY.md", m.group(1).lower(), int(m.group(2)), source[m.group(1).lower()])
        for m in _API_MODULE_PROSE_RE.finditer(text):
            _fail(failures, "docs/API_STABILITY.md", m.group(1).lower(), int(m.group(2)), source[m.group(1).lower()])
        _check_module_sum(failures, "docs/API_STABILITY.md", text, source)

    # docs/SECURITY_AUDIT.md: "(21 tools total: 7 OPP + 8 OL + 6 ORF)".
    path = root / "docs" / "SECURITY_AUDIT.md"
    if path.exists():
        for m in _TOTAL_PAREN_RE.finditer(read_text(path)):
            _fail(failures, "docs/SECURITY_AUDIT.md", "total", int(m.group(1)), total)

    # Per-module AGENTS.md: "## MCP tools (N total)".
    for rel, mod in (
        ("Omni_Pre_Processor/AGENTS.md", "opp"),
        ("Omni_Localizer/AGENTS.md", "ol"),
        ("Omni_Re_Formatter/AGENTS.md", "orf"),
    ):
        path = root / rel
        if not path.exists():
            continue
        for m in _MODULE_AGENTS_ANY_RE.finditer(read_text(path)):
            _fail(failures, rel, mod, int(m.group(1)), source[mod])

    # Per-repo README.md: "MCP Surface Mastery (N MCP tools)".
    for rel, mod in (
        ("Omni_Pre_Processor/README.md", "opp"),
        ("Omni_Localizer/README.md", "ol"),
        ("Omni_Re_Formatter/README.md", "orf"),
    ):
        path = root / rel
        if not path.exists():
            continue
        for m in _README_MCP_RE.finditer(read_text(path)):
            _fail(failures, rel, mod, int(m.group(1)), source[mod])

    # docs/PRD.md: "OPP (7 tools), OL (21 tools), ORF (6 tools)".
    path = root / "docs" / "PRD.md"
    if path.exists():
        for m in _PRD_LIST_RE.finditer(read_text(path)):
            _fail(failures, "docs/PRD.md", m.group(1).lower(), int(m.group(2)), source[m.group(1).lower()])

    # docs/SUITE_EXPECTATIONS.md: "7 + 21 + 6 = 34 tools" sum form.
    path = root / "docs" / "SUITE_EXPECTATIONS.md"
    if path.exists():
        _check_module_sum(failures, "docs/SUITE_EXPECTATIONS.md", read_text(path), source)

    # reports/SELF_DRIVEN_LOOP_V2_REPORT.md: "opp-mcp-server (7 tools) | ol-mcp (8 tools) | ...".
    path = root / "reports" / "SELF_DRIVEN_LOOP_V2_REPORT.md"
    if path.exists():
        text = read_text(path)
        m = re.search(
            r"opp-mcp-server\s*\((\d+)\s+tools?\).*?ol-mcp\s*\((\d+)\s+tools?\).*?orf-mcp-server\s*\((\d+)\s+tools?\)",
            text,
        )
        if m:
            opp_c, ol_c, orf_c = (int(g) for g in m.groups())
            _fail(failures, "reports/SELF_DRIVEN_LOOP_V2_REPORT.md", "opp", opp_c, source["opp"])
            _fail(failures, "reports/SELF_DRIVEN_LOOP_V2_REPORT.md", "ol", ol_c, source["ol"])
            _fail(failures, "reports/SELF_DRIVEN_LOOP_V2_REPORT.md", "orf", orf_c, source["orf"])

    # omni-docmap SKILL.md: "all 34 tools across ... (OPP 7 / OL 21 / ORF 6)".
    path = root / ".opencode" / "skills" / "omni-docmap" / "SKILL.md"
    if path.exists():
        text = read_text(path)
        m = re.search(r"all\s+(\d+)\s+tools\s+across", text)
        if m:
            _fail(failures, "omni-docmap SKILL.md", "total", int(m.group(1)), total)
        m = re.search(r"OPP\s+(\d+)\s*/\s*OL\s+(\d+)\s*/\s*ORF\s+(\d+)", text)
        if m:
            opp_c, ol_c, orf_c = (int(g) for g in m.groups())
            _fail(failures, "omni-docmap SKILL.md", "opp", opp_c, source["opp"])
            _fail(failures, "omni-docmap SKILL.md", "ol", ol_c, source["ol"])
            _fail(failures, "omni-docmap SKILL.md", "orf", orf_c, source["orf"])


