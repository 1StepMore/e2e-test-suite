def check_scenarios(root: Path, failures: list[str]) -> None:
    """Scenario count == 83 with tier split; input formats >= 13; '13+' claims.

    Skipped (report-only, not a failure) when ``scenarios/`` is absent.
    """
    scenarios = root / "scenarios"
    if not scenarios.is_dir():
        print("  scenarios/: absent -> skip (report-only, not a failure)")
        return
    yamls = sorted(p for p in scenarios.rglob("*.yaml") if p.is_file())
    total = len(yamls)
    tiers: dict[str, int] = {}
    for p in yamls:
        tier = "1"  # missing tier field defaults to tier 1 (plan: 79/3/1)
        for line in read_text(p).splitlines():
            if re.match(r"tier\s*:", line.strip()):
                tier = line.split(":", 1)[1].strip()
                break
        tiers[tier] = tiers.get(tier, 0) + 1
    print(f"  scenarios/: {total} yaml files; tiers={dict(sorted(tiers.items()))}")
    if total != 83:
        failures.append(f"scenarios/: {total} yaml files, expected 83")

    opp_dir = scenarios / "opp"
    if opp_dir.is_dir():
        opp_count = len([p for p in opp_dir.glob("*.yaml") if p.is_file()])
        print(f"  scenarios/opp: {opp_count} input-format scenarios")
        if opp_count < 13:
            failures.append(f"scenarios/opp: {opp_count} input formats, expected >= 13")
        for rel in ("AGENTS.md", "README.md"):
            path = root / rel
            if path.exists() and "13+" not in read_text(path):
                failures.append(f"{rel} must claim '13+' input formats")


def check_test_matrix(root: Path, failures: list[str]) -> None:
    """Canonical test-matrix (131/64/0) + nightly (14) claims; skip absent files."""
    proj = root / "PROJECT_STATUS.md"
    if proj.exists():
        text = read_text(proj)
        if "131 PASS, 64 SKIP, 0 FAIL" not in text:
            failures.append("PROJECT_STATUS.md must carry the canonical '131 PASS, 64 SKIP, 0 FAIL'")
        for m in re.finditer(r"(\d+)\s+PASS\b", text):
            if m.group(1) != "131":
                failures.append(f"PROJECT_STATUS.md claims {m.group(1)} PASS, canonical is 131")
    else:
        print("  PROJECT_STATUS.md: absent -> skip (report-only)")
    for rel in ("TESTS.md", "ACCEPTED_GAPS.md", "docs/SECURITY_AUDIT.md"):
        path = root / rel
        if not path.exists():
            continue
        for m in re.finditer(r"(\d+)\s+PASS\b", read_text(path)):
            if m.group(1) not in ("131", "0"):
                failures.append(f"{rel} claims {m.group(1)} PASS outside the canonical matrix")
    tes = root / "TESTS.md"
    if tes.exists() and "14 nightly tests" not in read_text(tes):
        failures.append("TESTS.md must carry '14 nightly tests'")
    ulw = root / "reports" / "ulw-loop-design.md"
    if ulw.exists():
        if "(--collect-only; canonical: 14)" not in read_text(ulw):
            failures.append("reports/ulw-loop-design.md must carry '(--collect-only; canonical: 14)'")


def check_version_sync(root: Path, failures: list[str]) -> None:
    """Delegate version-doc sync to scripts/sync_version_docs.py --check."""
    sync = root / "scripts" / "sync_version_docs.py"
    if not sync.exists():
        print("  scripts/sync_version_docs.py: absent -> warn-skip")
        return
    try:
        proc = subprocess.run(
            ["python3", str(sync), "--check"],
            cwd=str(root),
            capture_output=True,
            text=True,
            timeout=120,
        )
    except (subprocess.SubprocessError, OSError) as exc:
        failures.append(f"scripts/sync_version_docs.py --check could not run: {exc}")
        return
    if proc.returncode != 0:
        failures.append(
            f"scripts/sync_version_docs.py --check failed (rc={proc.returncode}): "
            f"{(proc.stdout or proc.stderr).strip()}"
        )


def check_stray(root: Path, failures: list[str]) -> None:
    """No tests/test_bug_*.py files may live in the shipped tree."""
    tests = root / "tests"
    if not tests.is_dir():
        print("  tests/: absent -> skip")
        return
    stray = sorted(tests.glob("test_bug_*"))
    if stray:
        names = ", ".join(p.name for p in stray)
        print(f"  Stray test_bug_* files: {names} -> FAIL")
        failures.append(f"tests/ contains {len(stray)} test_bug_* file(s): {names}")
    else:
        print("  Stray test_bug_* files in tests/: none -> ok")


def check_inventory(root: Path, failures: list[str]) -> None:
    """docs/dev/doc-inventory.md must exist and carry the AUTO-GENERATED header."""
    out = root / "docs" / "dev" / "doc-inventory.md"
    if not out.exists():
        print("  docs/dev/doc-inventory.md: missing -> FAIL")
        failures.append("docs/dev/doc-inventory.md missing — run python3 scripts/doc_inventory.py first")
        return
    text = read_text(out)
    first = text.splitlines()[0] if text.splitlines() else ""
    if first.startswith("<!-- AUTO-GENERATED by scripts/doc_inventory.py"):
        print("  docs/dev/doc-inventory.md: AUTO-GENERATED header present -> ok")
    else:
        print("  docs/dev/doc-inventory.md: AUTO-GENERATED header MISSING -> FAIL")
        failures.append(
            "docs/dev/doc-inventory.md is stale: missing its AUTO-GENERATED header — "
            "regenerate with python3 scripts/doc_inventory.py"
        )


def run_check(root: Path) -> list[str]:
    """Run all --check gates; return the list of human-readable failures."""
    failures: list[str] = []
    print("doc_inventory --check")

    # 1. Source truth (computed from the MCP source files, never hardcoded).
    source: dict[str, int] = {}
    src_paths = {
        "opp": root / "Omni_Pre_Processor" / "src" / "opp" / "mcp" / "server.py",
        "ol": root / "Omni_Localizer" / "src" / "ol_mcp" / "tools.py",
        "orf": root / "Omni_Re_Formatter" / "src" / "orf" / "mcp" / "server.py",
    }
    counters = {
        "opp": count_tool_schemas,
        "ol": count_tool_registry,
        "orf": count_listed_tools,
    }
    for key, path in src_paths.items():
        if path.exists():
            source[key] = counters[key](path)
        else:
            source[key] = 0
            print(f"  source {key}: {path.relative_to(root)} missing -> 0")
    total = source["opp"] + source["ol"] + source["orf"]
    print(f"SOURCE: OPP={source['opp']} OL={source['ol']} ORF={source['orf']} total={total}")

    # 2. Claim sites vs source truth.
    check_claim_sites(root, source, failures)

    # 3. Scenario count + input formats (skipped when scenarios/ absent).
    check_scenarios(root, failures)

    # 6. Test matrix + nightly claims.
    check_test_matrix(root, failures)

    # 7. Version sync (delegate).
    check_version_sync(root, failures)

    # 8. Stray test_bug_* files.
    check_stray(root, failures)

    # 9. Inventory freshness.
    check_inventory(root, failures)

    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the Omni Suite documentation inventory + run the "
        "source-truth --check (docs/dev/doc-inventory.md)."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify source-truth tool counts vs claim sites, scenario/test-matrix "
        "claims, version-sync delegation, stray test_bug_* files, and inventory "
        "freshness. No files are written. Exits 1 on any failure.",
    )
    parser.add_argument(
        "--root",
        default=str(ROOT),
        help="Rebase every relative path onto DIR (default: repo root).",
    )
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()

    if args.check:
        failures = run_check(root)
        print()
        if failures:
            print(f"check FAILED ({len(failures)} issue(s)):")
            for f in failures:
                print(f"  - {f}")
            return 1
        print("check passed: source truth matches claims, no stray files, inventory fresh.")
        return 0

    docs = root / "docs"
    out = docs / "dev" / "doc-inventory.md"
    rows = scan_docs(docs, out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_report(rows), encoding="utf-8")
    total_lines = sum(r["lines"] for r in rows)
    print(f"Wrote {out} ({len(rows)} files, {total_lines} lines).")
    print("Regenerate after doc changes; verify with --check (exit 0 = clean).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
