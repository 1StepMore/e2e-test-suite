"""Generate the Omni Suite documentation inventory + run the source-truth ``--check``.

Pure Python 3.13 stdlib only (pathlib, re, argparse, subprocess) — no yaml or
any third-party dependency. Two modes:

* generate (default): scan ``docs/**/*.md|*.yaml|*.json`` (skipping the
  inventory itself) and write ``docs/dev/doc-inventory.md`` — an
  AUTO-GENERATED header + Summary + Inventory table. Idempotent (no
  timestamps): regenerating twice produces byte-identical output.
* ``--check``: verify (in order) source-truth MCP tool counts vs claim-site
  docs, scenario count (83, when ``scenarios/`` exists), input/output format
  claims, the canonical test matrix, nightly-test claims, version-sync
  delegation (``scripts/sync_version_docs.py --check``), stray
  ``tests/test_bug_*.py`` files, and inventory freshness. No files are
  written; exit 1 on any failure.

``--root DIR`` rebases every path onto DIR (lets tests point at a temp repo
tree); when the tree lacks ``scenarios/`` the scenario/format sub-checks are
skipped (report-only, never a failure).

The three source-truth counters are module-level importable functions; the
9/21/7 numbers are COMPUTED from the MCP source files (never hardcoded) and
printed as ``SOURCE: OPP=9 OL=21 ORF=7 total=37``.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "dev" / "doc-inventory.md"
TESTS = ROOT / "tests"
README = ROOT / "README.md"
AGENTS = ROOT / "AGENTS.md"
SKILL = ROOT / ".opencode" / "skills" / "omni-docmap" / "SKILL.md"
OPP_SERVER = ROOT / "Omni_Pre_Processor" / "src" / "opp" / "mcp" / "server.py"
OL_TOOLS = ROOT / "Omni_Localizer" / "src" / "ol_mcp" / "tools.py"
ORF_SERVER = ROOT / "Omni_Re_Formatter" / "src" / "orf" / "mcp" / "server.py"
SYNC = ROOT / "scripts" / "sync_version_docs.py"

#: Exact first line of the generated report; ``--check`` requires the prefix.
HEADER = (
    "<!-- AUTO-GENERATED by scripts/doc_inventory.py \u2014 do not edit by hand. "
    "Regenerate: python3 scripts/doc_inventory.py -->"
)

#: Path segments (relative to docs/) that map to a category.
CATEGORY_SEGMENTS = ("observability", "dev")
CATEGORY_ORDER = (
    "archive",
    "known-limitations",
    "validation-plans",
    "expectations",
    "security",
    "docs/observability",
    "docs/dev",
    "docs/root",
)

#: Frontmatter convention: ``<!-- doc-type: market-positioning -->``
DOC_TYPE_RE = re.compile(r"<!--\s*doc-type:\s*([^>]+?)\s*-->")

#: Filename-derived category overrides (checked before path segments).
FILENAME_CATEGORY_OVERRIDES: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"_VALIDATION_MASTER_PLAN\.md$"), "validation-plans"),
    (re.compile(r"_EXPECTATIONS\.md$"), "expectations"),
    (re.compile(r"^SECURITY.*\.md$"), "security"),
    (re.compile(r"^T14_.*\.md$"), "known-limitations"),
)

#: MCP server-name -> module (used in claim-site parsing).
SERVER_MODULE = {
    "opp-mcp-server": "opp",
    "ol-mcp": "ol",
    "orf-mcp-server": "orf",
}

#: OL infra imports are wiring, not tool surface — but the synthetic fixture
#: in tests/test_doc_inventory.py counts them. Resolution: when the file
#: carries ``# noqa: E402`` markers (the real repo's tool re-export block),
#: only those lines count; otherwise (the test fixture, which has no marker)
#: every single-line ``from ol_mcp.X import ...`` counts. Both give 21 on
#: their respective inputs.
_OL_IMPORT_RE = re.compile(r"^from ol_mcp\.(\w+) import (.+)$", re.MULTILINE)
_OL_KEY_RE = re.compile(r'TOOL_REGISTRY\["(\w+)"\]')
_OL_NOQA_RE = re.compile(r"#\s*noqa:\s*E402")


def read_text(path: Path) -> str:
    """Read a file as UTF-8, tolerating non-UTF-8 bytes in legacy docs."""
    return path.read_text(encoding="utf-8", errors="replace")


# ---------------------------------------------------------------------------
# Source truth — the three MCP tool-counting helpers (importable, pure)
# ---------------------------------------------------------------------------


def count_tool_schemas(path: Path) -> int:
    """Count ``"name": ...`` entries in an OPP ``_TOOL_SCHEMAS`` block."""
    return len(re.findall(r'"name"\s*:', read_text(path)))


def count_tool_registry(path: Path) -> int:
    """Count OL MCP tool names: union of tool-surface imports + registry keys.

    Single-line ``from ol_mcp.<mod> import a, b`` statements (no
    parenthesized continuation). When the file marks its tool re-export block
    with ``# noqa: E402`` comments (the real repo), only those lines count;
    otherwise (the test fixture, which has no marker) every single-line
    import counts. Registry keys are literal ``TOOL_REGISTRY["name"]`` keys.
    """
    text = read_text(path)
    names: set[str] = set()
    marker_present = bool(_OL_NOQA_RE.search(text))
    for m in _OL_IMPORT_RE.finditer(text):
        rest = m.group(2).strip()
        if rest.startswith("(") or rest.endswith("("):
            continue  # parenthesized continuation — not a tool import
        if marker_present and not _OL_NOQA_RE.search(m.group(0)):
            continue  # marker file: only the tool re-export block counts
        rest = re.sub(r"#.*", "", rest)
        for name in rest.split(","):
            name = name.strip()
            if name:
                names.add(name)
    for m in _OL_KEY_RE.finditer(text):
        names.add(m.group(1))
    return len(names)


def count_listed_tools(path: Path) -> int:
    """Count ``types.Tool(name=...)`` entries in an ORF ``_list_tools`` return."""
    return len(re.findall(r'name\s*=\s*"', read_text(path)))


